# --------------------------------------------------------------------------
# 附录 2 物性参数（问题 1）
# --------------------------------------------------------------------------
RHO = 820.0            # kg/m^3     密度
CP = 2600.0            # J/(kg·K)   比热容
K_COND = 0.36          # W/(m·K)    热传导系数
H_CONV = 25.0          # W/(m^2·K)  对流换热系数
KM_CONV = 8.0e-7       # m/s        对流传质系数

# 水分浓度扩散系数经验公式：D = 7e-9 * exp(-0.89 / C)
D0 = 7.0e-9
D_EXP_COEF = 0.89

# 初始条件
T_INIT = 28.0          # 摄氏度
C_INIT = 2.55          # kg/kg（干基）

# 数值下限：C 趋于 0 时 D 趋于 0，公式中 C 出现在分母，取一个极小正数保护
C_FLOOR = 1.0e-8


def props_const(T, C):
    """返回 (rho, cp, k)。问题 1 中三者均为常数，与温度、含水率无关。"""
    T = np.asarray(T, dtype=float)
    return (np.full_like(T, RHO), np.full_like(T, CP), np.full_like(T, K_COND))


def D_of_C(C):
    """附录 2：D = 7e-9 * exp(-0.89/C)，单位 m^2/s。"""
    C = np.maximum(np.asarray(C, dtype=float), C_FLOOR)
    return D0 * np.exp(-D_EXP_COEF / C)


def D_fun_p1(C, T=None):
    """问题 1 的扩散系数只依赖含水率 C。"""
    return D_of_C(C)


